const PLACE_WORDS: { place: RiddlePlace; starts: string[]; exact: string[] }[] = [
  { place: 'lobby', starts: ['לובי', 'קבלה', 'כניסה', 'מבואה', 'מעלי', 'טרקלין'], exact: [] },
  { place: 'pool', starts: ['בריכ', 'ג׳קוזי', "ג'קוזי", 'שחיי', 'מגלש'], exact: ['ים', 'חוף', 'ספא', 'אגם'] },
  { place: 'dining', starts: ['מסעד', 'מזנון', 'ארוח', 'מטבח', 'קפיטרי'], exact: ['אוכל', 'בר', 'קפה'] },
  { place: 'garden', starts: ['גינ', 'מדשא', 'חורש', 'פארק', 'שביל', 'מרפס'], exact: ['גן', 'דשא', 'חצר', 'יער', 'בוסתן'] },
];

/** Best guess of what kind of place a spot is, from its name ("ליד הבריכה" → pool). */
export function placeOfSpotName(name: string): RiddlePlace {
  const words = (name || '').split(/[^א-ת׳']+/).filter(Boolean);
  // "בבריכה" / "לחוף" / "הגינה": also try the word without its one-letter prefix.
  const forms = words.flatMap((w) => (w.length > 2 && 'הבלמו'.includes(w[0]) ? [w, w.slice(1)] : [w]));
  for (const { place, starts, exact } of PLACE_WORDS) {
    if (forms.some((w) => exact.includes(w) || starts.some((s) => w.startsWith(s)))) return place;
  }
  return 'any';
}

// ---------------------------------------------------------------- picking

const norm = (s: string) => (s || '').replace(/\s+/g, ' ').trim();

/** What an adventure already uses, so the bank never offers the same riddle twice. */
function usedBy(riddles: Pick<TheCodeRiddle, 'text' | 'answerWord'>[]): { texts: Set<string>; answers: Set<string> } {
  return {
    texts: new Set(riddles.map((r) => norm(r.text)).filter(Boolean)),
    answers: new Set(riddles.map((r) => norm(r.answerWord)).filter(Boolean)),
  };
}

function placeRank(riddle: BankRiddle, place: RiddlePlace): number {
  if (riddle.place === place) return 0;
  if (riddle.place === 'any') return 1;
  return 2;
}

/**
 * Bank riddles for the picker: optional letter, best-fitting place first, the ones this
 * adventure already uses left out.
 */
export function suggestFromBank(opts: {
  letter?: string | null;
  place?: RiddlePlace;
  /** Only this level; absent = every level, easiest first. */
  difficulty?: 1 | 2 | 3 | null;
  riddles?: Pick<TheCodeRiddle, 'text' | 'answerWord'>[];
}): BankRiddle[] {
  const used = usedBy(opts.riddles || []);
  const place = opts.place || 'any';
  return RIDDLE_BANK
    .map((r, i) => ({ r, i }))
    .filter(({ r }) => !used.texts.has(norm(r.text)) && !used.answers.has(norm(r.answerWord)))
    .filter(({ r }) => !opts.letter || bankLetter(r) === opts.letter)
    .filter(({ r }) => !opts.difficulty || r.difficulty === opts.difficulty)
    .sort((a, b2) => placeRank(a.r, place) - placeRank(b2.r, place) || a.r.difficulty - b2.r.difficulty || a.i - b2.i)
    .map(({ r }) => r);
}

// ---------------------------------------------------------------- one-click fill

export interface BankFillItem {
  gnomeId: string;
  bank: BankRiddle;
  letter: string;
  /** The phrase this riddle was added for; absent = "so the gnome is not empty". */
  phraseId?: string;
}

export interface BankFillPlan {
  add: BankFillItem[];
  /** What the bank could not solve — the operator has to act. */
  unfilled: { phraseId: string; letter: string; why: 'notEnoughGnomes' | 'bankEmpty' }[];
}

/**
 * Plans the riddles to add from the bank so that every active phrase can be collected
 * (each letter of a phrase from a DIFFERENT gnome — the engine's rule) and no usable gnome
 * is left without a riddle. Existing published riddles are used first; nothing is changed
 * or removed. The caller adds the planned riddles as `published`.
 */
export function planBankFill(
  config: Pick<TheCodeConfig, 'spots' | 'gnomes' | 'phrases'>,
  riddles: TheCodeRiddle[]
): BankFillPlan {
  const spots = new Map((config.spots || []).map((s) => [s.id, s] as const));
  const gnomes = (config.gnomes || [])
    .filter((g) => g.isActive && spots.get(g.spotId)?.isActive)
    .sort((a, b2) => a.number - b2.number);
  const placeOf = new Map(gnomes.map((g) => [g.id, placeOfSpotName(spots.get(g.spotId)?.name || '')] as const));

  /** Letters each gnome can already give (published riddles + what this plan adds). */
  const gives = new Map<string, Set<string>>(gnomes.map((g) => [g.id, new Set<string>()] as const));
  const count = new Map<string, number>(gnomes.map((g) => [g.id, 0] as const));
  for (const r of riddles || []) {
    if (!gives.has(r.gnomeId)) continue;
    count.set(r.gnomeId, (count.get(r.gnomeId) || 0) + 1);
    const letter = letterOfAnswer(r.answerWord || '');
    if (r.status === 'published' && letter) gives.get(r.gnomeId)!.add(letter);
  }

  const used = usedBy(riddles || []);
  const add: BankFillItem[] = [];
  const unfilled: BankFillPlan['unfilled'] = [];

  const take = (letter: string, gnomeId: string): BankRiddle | null => {
    const place = placeOf.get(gnomeId) || 'any';
    const pick = RIDDLE_BANK
      .filter((r) => bankLetter(r) === letter && !used.texts.has(norm(r.text)) && !used.answers.has(norm(r.answerWord)))
      .sort((a, b2) => placeRank(a, place) - placeRank(b2, place) || a.difficulty - b2.difficulty)[0];
    if (!pick) return null;
    used.texts.add(norm(pick.text));
    used.answers.add(norm(pick.answerWord));
    return pick;
  };
  const give = (gnomeId: string, letter: string, phraseId?: string): boolean => {
    const bank = take(letter, gnomeId);
    if (!bank) return false;
    add.push({ gnomeId, bank, letter, ...(phraseId ? { phraseId } : {}) });
    gives.get(gnomeId)!.add(letter);
    count.set(gnomeId, (count.get(gnomeId) || 0) + 1);
    return true;
  };

  const demand = new Map<string, number>();
  for (const phrase of config.phrases || []) {
    if (!phrase.isActive) continue;
    const letters = phraseLetters(phrase.text || '');
    if (letters.length < 2) continue;
    for (const l of letters) demand.set(l, (demand.get(l) || 0) + 1);
    if (letters.length > gnomes.length) {
      unfilled.push({ phraseId: phrase.id, letter: '', why: 'notEnoughGnomes' });
      continue;
    }

    // Maximum matching slot → gnome over what the gnomes already give (Kuhn).
    const slotOfGnome = new Map<string, number>();
    const tryAssign = (slot: number, seen: Set<string>): boolean => {
      for (const g of gnomes) {
        if (seen.has(g.id) || !gives.get(g.id)!.has(letters[slot])) continue;
        seen.add(g.id);
        const other = slotOfGnome.get(g.id);
        if (other === undefined || tryAssign(other, seen)) {
          slotOfGnome.set(g.id, slot);
          return true;
        }
      }
      return false;
    };
    for (let i = 0; i < letters.length; i++) tryAssign(i, new Set());
    const matched = new Set(slotOfGnome.values());

    // The rest: a free gnome (fewest riddles first) gets a bank riddle for the letter.
    for (let i = 0; i < letters.length; i++) {
      if (matched.has(i)) continue;
      const free = gnomes
        .filter((g) => !slotOfGnome.has(g.id))
        .sort((a, b2) => (count.get(a.id) || 0) - (count.get(b2.id) || 0) || a.number - b2.number);
      const host = free.find((g) => give(g.id, letters[i], phrase.id));
      if (!host) {
        unfilled.push({ phraseId: phrase.id, letter: letters[i], why: 'bankEmpty' });
        continue;
      }
      slotOfGnome.set(host.id, i);
    }
  }

  // No gnome stays empty: the letter the phrases need most compared with how many gnomes
  // give it, then anything the bank has for this kind of place.
  for (const g of gnomes) {
    if ((count.get(g.id) || 0) > 0) continue;
    const supply = (l: string) => gnomes.filter((x) => gives.get(x.id)!.has(l)).length;
    const wanted = [...demand.keys()].sort((a, b2) => supply(a) - demand.get(a)! - (supply(b2) - demand.get(b2)!));
    const place = placeOf.get(g.id) || 'any';
    const letters = [...wanted, ...suggestFromBank({ place }).map(bankLetter)];
    letters.some((l) => give(g.id, l));
  }

  return { add, unfilled };
}
