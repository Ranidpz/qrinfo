// הקוד — ready-made riddles for operators who do not know what to write.
// PURE: no I/O. Used by the operator admin only (never sent to players as a bank).
//
// Every riddle is a "what am I?" a child can solve anywhere, so a demo game can be built
// in minutes. `place` only says where a riddle feels most at home (the answer is something
// you typically see there); a riddle from any place still works on any gnome.
// The collector letter is the first letter of `answerWord` — exactly as in the game.
//
// Writing rules (tested in scripts/tests/thecode-riddlebank.test.mjs):
// the text and the hints never contain the answer; one clear answer; plural "you" (לשון רבים).
//
// `difficulty` 1/2/3 = קלה / בינונית / קשה. The picker can show one level only; the one-click
// fill always prefers the easiest, so a hard riddle is never forced on an operator.

import type { TheCodeConfig, TheCodeRiddle } from '@/types/thecode';
import { letterOfAnswer, phraseLetters } from './letters';

export type RiddlePlace = 'any' | 'lobby' | 'pool' | 'dining' | 'garden';

export interface BankRiddle {
  /** Stable: `${place}:${answerWord}`. */
  id: string;
  place: RiddlePlace;
  text: string;
  answerWord: string;
  /** Graded: [gentle, almost there]. */
  hints: string[];
  difficulty: 1 | 2 | 3;
}

