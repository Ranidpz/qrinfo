// Hebrew print + mounting instructions shown next to the 3D-print button (plural form, short lines).
import type { Print3DMount, Print3DShape } from './presets';

export interface InstructionGroup {
  title: string;
  steps: string[];
}

export function instructionsFor(shape: Print3DShape, mount: Print3DMount, opts: { batch: boolean; backNumber: boolean }): InstructionGroup[] {
  const groups: InstructionGroup[] = [
    {
      title: 'הדפסת הלוחיות (לבן ושחור)',
      steps: [
        'פתחו את הקובץ בתוכנה של במבו. הוא נפתח מוכן, עם שני הצבעים.',
        'ודאו שעל המדפסת מותקן המשטח המחוספס. הוא נותן לקוד פנים מט, בלי ברק.',
        'בקובץ, חומר 1 הוא השחור וחומר 2 הוא הלבן. במסך השליחה בדקו שכל אחד מחובר לגליל הנכון.',
        'הלוחיות מודפסות עם הקוד כלפי מטה, ולכן בתוכנה הקוד נראה הפוך. זה בכוונה — הוא יוצא נכון.',
        opts.batch
          ? 'לפני פלטה מלאה הדפיסו לוחית אחת וסרקו אותה: באייפון, באנדרואיד ובסורק של המשחק.'
          : 'אחרי ההדפסה סרקו את הלוחית: באייפון, באנדרואיד ובסורק של המשחק.',
        'חכו שהפלטה תתקרר, ורק אז הורידו את הלוחיות — כך הן לא מתעקמות.',
      ],
    },
  ];

  if (shape === 'base') {
    groups.push({
      title: 'הבסיס השחור',
      steps: [
        'הבסיס מודפס בשחור בלבד (חומר 1), עם השקע כלפי מעלה. הוא מגיע בקובץ נפרד.',
        mount === 'screws'
          ? 'הבריגו את הבסיס לקיר עם שני ברגי עץ בעובי 3.5 עד 4 מ״מ. הראשים שוקעים בתוך השקע, והלוחית מסתירה אותם.'
          : 'הדביקו בגב הבסיס סרט דו־צדדי חזק. נקו את הקיר באלכוהול, ולחצו על הבסיס חצי דקה.',
        'לחצו את הלוחית לשקע עד שהפינים נכנסים לחורים. הפינים לא סימטריים — יש רק כיוון אחד נכון.',
        'כדי להחליף לוחית בלי כלים — אל תשימו דבק. כדי שלא יוציאו אותה — טיפת דבק מגע בשקע.',
        'בחוץ הדפיסו את הבסיס מחומר לחוץ (שחור עמיד לשמש).',
      ],
    });
  }
  if (shape === 'stand') {
    groups.push({
      title: 'המעמד',
      steps: [
        'קובץ המעמד יתווסף בשלב הבא. בינתיים אפשר להדפיס את הלוחיות.',
        'לחצו את הלוחית לשקע בחזית המעמד עד שהפינים נכנסים.',
      ],
    });
  }
  if (shape === 'gnome') {
    groups.push({
      title: 'התקנה בגמד',
      steps: [
        'לחצו את הלוחית לשקע בבטן של הגמד עד שהפינים נכנסים לחורים.',
        'בגמדים ישנים השקע רדוד והלוחית בולטת קצת — הדביקו אותה בדבק.',
      ],
    });
  }
  if (shape === 'keychain') {
    groups.push({
      title: 'מחזיק המפתחות',
      steps: [
        'הקוד במחזיק קטן מאוד. הדפיסו אחד, סרקו אותו, ורק אז הדפיסו עוד.',
        'השחילו טבעת מפתחות בחור שבראש המחזיק.',
      ],
    });
  }
  if (opts.backNumber) {
    groups[0].steps.push('המספר בגב כל לוחית הוא מספר הקוד — כך יודעים איזו לוחית שייכת לאיזה מקום.');
  }
  return groups;
}
